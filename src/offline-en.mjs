export function runOfflineEn(argv = []) {
    const checkOnly = argv.includes('--check')
    const { sourceLocale, reportsDir, root } = getContext()
    const zh = load(sourceLocale)
    const en = load('en-US')
    let kept = 0
    let filled = 0
    const leftover = []

    for (const key of Object.keys(zh)) {
        if (isMetaKey(key)) continue
        const current = en[key]
        if (isAlreadyEnglish(key, current)) {
            kept++
            continue
        }
        const translated = translateOffline(key)
        if (!translated || translated === key || looksChinese(translated)) {
            leftover.push(key)
            continue
        }
        if (!checkOnly) {
            en[key] = translated
        }
        filled++
    }

    console.log(`[i18n:offline-en] already English (KEEP): ${kept}`)
    console.log(`[i18n:offline-en] would/filled: ${filled}`)
    console.log(`[i18n:offline-en] still chinese-ish: ${leftover.length}`)

    fs.mkdirSync(reportsDir, { recursive: true })
    const leftoverPath = path.join(reportsDir, 'i18n-offline-leftover.json')
    fs.writeFileSync(leftoverPath, JSON.stringify([...new Set(leftover)], null, 2), 'utf8')
    console.log(`[i18n:offline-en] leftover -> ${path.relative(root, leftoverPath)}`)

    if (checkOnly) {
        console.log('[i18n:offline-en] check-only, no write')
        return
    }

    save('en-US', en)
    console.log('[i18n:offline-en] wrote en-US.json')
}
