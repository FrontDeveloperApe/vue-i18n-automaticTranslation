const PREFIX_RULES = [
    [/^请输入/, 'Please enter '],
    [/^请选择/, 'Please select '],
    [/^请添加/, 'Please add '],
    [/^请填写/, 'Please fill in '],
    [/^请先/, 'Please '],
    [/^请再次/, 'Please re-'],
    [/^请至少/, 'Please at least '],
    [/^请仔细/, 'Please carefully '],
    [/^确定要/, 'Confirm to '],
    [/^确认/, 'Confirm ']
]

function applyTerms(text) {
    let out = text
    const keys = Object.keys(TERMS).sort((a, b) => b.length - a.length)
    for (const k of keys) {
        if (out.includes(k)) out = out.split(k).join(TERMS[k])
    }
    return out
}

